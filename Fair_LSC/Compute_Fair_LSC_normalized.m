function [Fair_LSC_normalized_clusterlabels,Fair_LSC_normalized_Avg_Balance,Fair_LSC_normalized_Avg_Fraction] = Compute_Fair_LSC_normalized(data,k,opts)
% label = LSC(data,k,opts): Landmark-based Spectral Clustering
% Input:
%       - data: the data matrix of size nSmp x nFea, where each row is a sample
%               point
%       - k: the number of clusters
%       opts: options for this algorithm
%           - p: the number of landmarks picked (default 1000)
%           - r: the number of nearest landmarks for representation (default 5)
%           - numRep: the number of replicates for the final kmeans (default 10)
%           - maxIter: the maximum number of iterations for final kmeans (default 100)
%           - mode: landmark selection method, currently support
%               - 'kmeans': use centers of clusters generated by kmeans (default)
%               - 'random': use randomly sampled points from the original
%                           data set 
%           The following parameters are effective ONLY in mode 'kmeans'
%           - kmNumRep: the number of replicates for initial kmeans (default 1)
%           - kmMaxIter: the maximum number of iterations for initial kmeans (default 5)
% Output:
%       - label: the cluster assignment for each point
% Requre:
%       litekmeans.m
% Usage:
%       data = rand([100,50]);
%       label = LSC(data,10);
%Reference:
%
%	Xinlei Chen, Deng Cai, "Large Scale Spectral Clustering with
%	Landmark-Based Representation," AAAI 2011. 
%
%   version 2.0 --Dec./2011 
%   version 1.0 --Oct./2010 
%
%   Written by Xinlei Chen (endernewton AT gmail.com)
%              Deng Cai (dengcai AT gmail.com)



%% 设置默认参数
if (~exist('opts','var'))
   opts = [];
end


p = 10;
if isfield(opts,'p')
    p = opts.p;
end

r = 2;
if isfield(opts,'r')
    r = opts.r;
end

maxIter = 100;
if isfield(opts,'maxIter')
    maxIter = opts.maxIter;
end

numRep = 10;
if isfield(opts,'numRep')
    numRep = opts.numRep;
end

mode = 'kmeans';
if isfield(opts,'mode')
    mode = opts.mode;
end

nSmp=size(data,1);

%% 使用K-means 选择 Landmark,注意kmMaxIter和kmNumRep仅在k-means下可用。
if strcmp(mode,'kmeans')
    kmMaxIter = 5;
    if isfield(opts,'kmMaxIter')
        kmMaxIter = opts.kmMaxIter;
    end
    kmNumRep = 1;
    if isfield(opts,'kmNumRep')
        kmNumRep = opts.kmNumRep;
    end
    [dump,marks]=litekmeans(data,p,'MaxIter',kmMaxIter,'Replicates',kmNumRep);
    clear kmMaxIter kmNumRep
elseif strcmp(mode,'random')
    indSmp = randperm(nSmp);
    marks = data(indSmp(1:p),:);
    clear indSmp
else
    error('mode does not support!');
end

%% 构建Z目的是建造相似性矩阵W
D = EuDist2(data,marks,0);
%% 设置高斯核函数的带宽参数 sigma,用于控制相似度的衰减速度
if isfield(opts,'sigma')
    sigma = opts.sigma;
else
    sigma = mean(mean(D));
end
%% 初始化变量
dump = zeros(nSmp,r);
idx = dump;
%% 找到每个数据点的最近 r 个 Landmark
for i = 1:r
    [dump(:,i),idx(:,i)] = min(D,[],2);
    temp = (idx(:,i)-1)*nSmp+[1:nSmp]';
    D(temp) = 1e100; 
end
%% 计算高斯核相似度
dump = exp(-dump/(2*sigma^2));
%% 归一化相似度
sumD = sum(dump,2);
%% 构建稀疏矩阵 Z
Gsdx = bsxfun(@rdivide,dump,sumD);
Gidx = repmat((1:nSmp)',1,r);
Gjdx = idx;
Z=sparse(Gidx(:),Gjdx(:),Gsdx(:),nSmp,p);
%% 图分解，将矩阵Z的每一列归一化
feaSum = full(sqrt(sum(Z,1)));
feaSum = max(feaSum, 1e-12);
Z = Z./feaSum(ones(size(Z,1),1),:);
Z=double(Z);
Z=Z';
fprintf('----------进行相似性矩阵构造Z大小为------------\n');
disp(size(Z));
%% 选取整个数据集的敏感属性Group
Group = readmatrix('E:\ZhongLongFei_Code\FairLeaSC\databases\Hcv_data_senvitive.csv');
%% 标准对称规范化的Fair_LSC_normalized
[B,Q,N]=Fair_LSC_normalized(Z,Group);
% 将归一化后的Z进行奇异值分解(SVD)得到V
%% Z进行奇异值分解SVD
[~,~,V]= mySVD(N,k+1);%对归一化后的 Z 进行奇异值分解（SVD）,提取前 k+1 个奇异向量
%normNFair=adj*B*Q逆,V=normNFair'*U*S逆
V(:,1) = [];
V=V./repmat(sqrt(sum(V.^2,2)),1,k);
%% 将V进行k-means得到聚类标签(标准对称规范化的Fair SC)
H=(B/Q)*V;%这里B/Q=B*Q逆，所以H=B*Q逆*N'*U*S逆=B*Q逆*V，其中V=N'*U*S逆
Fair_LSC_normalized_clusterlabels=litekmeans(H,k,'MaxIter',maxIter,'Replicates',numRep);
%% 调用标准LSC_normalized
fprintf('----------Fair_LSC_normalized的结果------------\n');
%% 调用平衡性 ComputeBalance
Fair_LSC_normalized_Avg_Balance = Fair_LSC_Balance(Fair_LSC_normalized_clusterlabels, Group);
fprintf('----------Fair_LSC_Avg_Balance为------------\n');
disp(Fair_LSC_normalized_Avg_Balance);
%% 调用得分情况 ComputeFraction
Fair_LSC_normalized_Avg_Fraction = Fair_LSC_Fraction(Fair_LSC_normalized_clusterlabels, Group);
fprintf('---------- Fair_LSC_norm_Avg_Fraction为------------\n');
disp(Fair_LSC_normalized_Avg_Fraction);



